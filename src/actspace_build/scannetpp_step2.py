"""ScanNet++ Step 2: blur filtering and keyframe selection (see docs/data_construction.md), one keyframe montage per scene,
report reports/scannetpp_step2_keyframes.md.

Candidate frames = Step 1 frames_all.json (10 FPS decoded frames minus POSE_FRAME_INVALID frames). Selection reuses
step2_keyframes.keyframes_scene: every ScanNet++ frame has depth with the same frame ID, so ARKit's depth-timestamp
matching constraint is not applied (keyframe_require_depth_match only applies to arkitscenes).

Usage: python -m actspace_build.scannetpp_step2 run [--scenes ...] [--force]
       python -m actspace_build.scannetpp_step2 report
"""
from __future__ import annotations

import argparse
import json

import cv2
import numpy as np

from .common import load_config, path_of, read_json
from .scannetpp import sp_cfg, sp_root, sp_work
from .step2_keyframes import keyframes_scene

DATASET = "scannetpp"


def montage(sid: str, out_path, n: int = 24, cols: int = 6, tile_w: int = 320) -> int:
    """Montage of n keyframes sampled uniformly in time; each tile is labelled with frame ID, time and Laplacian variance. Returns the number of keyframes used."""
    cfg = load_config()
    wd = sp_work(cfg) / sid
    kf = read_json(wd / "keyframes.json")
    frames = {f["frame_id"]: f for f in read_json(wd / "frames_all.json")}
    ids = kf["keyframe_ids"]
    if not ids:
        return 0
    pick = [ids[i] for i in np.unique(np.linspace(0, len(ids) - 1, min(n, len(ids))).round().astype(int))]
    t0 = min(f["timestamp"] for f in frames.values())
    tiles = []
    for fid in pick:
        f = frames[fid]
        img = cv2.imread(str(sp_root(cfg) / f["rel_path"]))
        lap = cv2.Laplacian(cv2.cvtColor(img, cv2.COLOR_BGR2GRAY), cv2.CV_64F).var()
        h = int(round(img.shape[0] * tile_w / img.shape[1]))
        img = cv2.resize(img, (tile_w, h), interpolation=cv2.INTER_AREA)
        txt = f"{f['source_frame'].replace('frame_', '')} t={f['timestamp'] - t0:.0f}s lap={lap:.0f}"
        cv2.rectangle(img, (0, 0), (tile_w, 18), (0, 0, 0), -1)
        cv2.putText(img, txt, (4, 13), cv2.FONT_HERSHEY_SIMPLEX, 0.42, (255, 255, 255), 1, cv2.LINE_AA)
        tiles.append(img)
    h = tiles[0].shape[0]
    while len(tiles) % cols:
        tiles.append(np.zeros_like(tiles[0]))
    rows = [np.concatenate(tiles[i:i + cols], axis=1) for i in range(0, len(tiles), cols)]
    sheet = np.concatenate(rows, axis=0)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(out_path), sheet, [cv2.IMWRITE_JPEG_QUALITY, 85])
    return len(pick)


def magenta_fraction(path) -> float:
    """Fraction of pure magenta pixels (ScanNet++ anonymisation patches) in the image."""
    img = cv2.imread(str(path))
    b, g_, r = img[..., 0].astype(int), img[..., 1].astype(int), img[..., 2].astype(int)
    return float(np.mean((r > 200) & (b > 200) & (g_ < 60)))


def magenta_stats(cfg: dict, sid: str) -> dict:
    """Fraction of keyframes containing magenta patches (pixel fraction > 0.1% counts). Cached in keyframes_magenta.json."""
    wd = sp_work(cfg) / sid
    cache = wd / "keyframes_magenta.json"
    kf = read_json(wd / "keyframes.json")
    if cache.exists() and read_json(cache).get("keyframe_ids") == kf["keyframe_ids"]:
        return read_json(cache)
    frames = {f["frame_id"]: f for f in read_json(wd / "frames_all.json")}
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(8) as ex:
        fr = list(ex.map(lambda fid: magenta_fraction(sp_root(cfg) / frames[fid]["rel_path"]), kf["keyframe_ids"]))
    fr = np.array(fr)
    res = {"keyframe_ids": kf["keyframe_ids"], "fractions": fr.tolist(), "num_with_mask": int((fr > 1e-3).sum()),
           "frac_with_mask": float((fr > 1e-3).mean()), "max_fraction": float(fr.max()) if len(fr) else 0.0}
    from .common import write_json
    write_json(cache, res)
    return res


def write_report(cfg: dict) -> None:
    sc = sp_cfg(cfg)
    fc = cfg["frames"]
    rep = path_of(cfg, "reports")
    img_dir = rep / "scannetpp_step2"
    L = ["# ScanNet++ Step 2: blur filtering and keyframe selection (5 pilot scenes)", "",
         "> Branch `scannetpp`. Generated by `python -m actspace_build.scannetpp_step2 report`. Reference: Step 2 in docs/data_construction.md.", "",
         "Rules:",
         "- Candidate frames: 10 FPS decoded frames minus `POSE_FRAME_INVALID` frames (bad or unverified in GATE A), i.e. Step 1 `frames_all.json`.",
         f"- Blur filter: frames whose Laplacian variance is below the scene's {fc['blur_drop_percentile']}th percentile **or** below scene median × {fc['blur_min_rel_to_median']} are dropped (`BLURRY`); the stricter threshold applies.",
         f"- Keyframes: in temporal order, the first frame with translation ≥ {fc['keyframe_min_translation_m']} m or |Δyaw| ≥ {fc['keyframe_min_rotation_deg']}° relative to the previous keyframe is the trigger frame; "
         f"within ±{fc['keyframe_sharpest_window_s']} s of it (and after the previous keyframe) the frame with the highest Laplacian variance is taken. Every ScanNet++ frame has depth with the same frame ID, so no depth-matching constraint is applied.",
         f"- Scenes with < {fc['min_keyframes_per_scene']} keyframes are dropped (`TOO_FEW_KEYFRAMES`).",
         "- Implementation: reuses the shared module `step2_keyframes.keyframes_scene` (unchanged); ScanNet++ only supplies the scene list, data root and montages.", "",
         "| Scene | Type | Decoded frames | POSE_FRAME_INVALID | Candidate frames | Blur dropped | Threshold: percentile / median ratio | Dropped by median ratio only | Median Laplacian variance: candidates → keyframes | Keyframes | GATE A estimate | Result |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    types = json.load(open(sp_root(cfg) / "metadata" / "scene_types.json"))
    failed = []
    for sid in sc["pilot_scenes"]:
        wd = sp_work(cfg) / sid
        k = read_json(wd / "keyframes.json")
        ga = read_json(wd / "gate_a.json")
        n_dec = ga["n_decoded_frames"]
        n_inv = ga["n_frames_dropped"]
        assert n_dec - n_inv == k["num_frames"], sid
        ok = k["scene_ok"]
        if not ok:
            failed.append(sid)
        L.append(f"| `{sid}` | {types.get(sid, '?')} | {n_dec} | {n_inv} | {k['num_frames']} | "
                 f"{k['num_blurry']} ({k['num_blurry'] / k['num_frames']:.0%}) | {k['blur_threshold_percentile']:.1f} / {k['blur_threshold_rel_median']:.1f} | "
                 f"{k['num_blurry_rel_only']} | {k['frame_lapvar_median']:.0f} → {k['keyframe_lapvar_median']:.0f} | **{k['num_keyframes']}** | "
                 f"{ga['num_keyframes_est']} | {'pass' if ok else 'TOO_FEW_KEYFRAMES'} |")
    L += ["", "### Observation: magenta patches in the images", "",
          "ScanNet++ iPhone images contain pure magenta patches (apparently text, paper, faces, etc. masked by the dataset for anonymisation, e.g. the notice on the wall in `5ee7c22ba0`). "
          "They do not affect blur filtering or keyframe selection, but they appear in the images the model sees. Fraction of keyframes with patches (magenta pixels > 0.1%):", "",
          "| Scene | Keyframes | Keyframes with patches | Max fraction in a single frame |", "|---|---|---|---|"]
    for sid in sc["pilot_scenes"]:
        m = magenta_stats(cfg, sid)
        L.append(f"| `{sid}` | {len(m['keyframe_ids'])} | {m['num_with_mask']} ({m['frac_with_mask']:.0%}) | {m['max_fraction']:.1%} |")
    L += ["", "Whether these need handling (e.g. avoiding frames with large patches when generating questions) is left as an open question."]
    L += ["", f"Scenes with fewer than {fc['min_keyframes_per_scene']} keyframes: {', '.join(f'`{s}`' for s in failed) if failed else 'none'}.", "",
          "\"GATE A estimate\" is the keyframe count estimated with the same rules during GATE A (used for the \"< 40 keyframes after removing bad frames\" check); the two should match.", "",
          "## Keyframe montages", "",
          "Per scene, 24 keyframes sampled uniformly in time (all of them if fewer than 24); each tile shows the original frame ID, seconds since video start and Laplacian variance.", ""]
    for sid in sc["pilot_scenes"]:
        L += [f"### `{sid}` ({types.get(sid, '?')})", "", f"![{sid}](scannetpp_step2/{sid}_keyframes.jpg)", ""]
    L += ["## Outputs", "",
          "- Per scene `work/scannetpp/<scene_id>/keyframes.json` (candidate frame count, blur thresholds, keyframe frame_id list); blur-drop details in `dropped.jsonl` (`BLURRY`).",
          f"- Montages: `reports/scannetpp_step2/<scene_id>_keyframes.jpg` (images not tracked in git)."]
    (rep / "scannetpp_step2_keyframes.md").write_text("\n".join(L) + "\n")
    print("wrote", rep / "scannetpp_step2_keyframes.md")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["run", "report"])
    ap.add_argument("--scenes", nargs="*")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    cfg = load_config()
    scenes = args.scenes or sp_cfg(cfg)["pilot_scenes"]
    if args.cmd == "run":
        for sid in scenes:
            r = keyframes_scene(DATASET, sid, sp_root(cfg), args.force)
            print(sid, {k: v for k, v in r.items() if k != "keyframe_ids"}, flush=True)
            montage(sid, path_of(cfg, "reports") / "scannetpp_step2" / f"{sid}_keyframes.jpg")
    write_report(cfg)


if __name__ == "__main__":
    main()
