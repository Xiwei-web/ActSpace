def load_scene_objs(cfg, sid):
    wd = sp_work(cfg) / sid
    objs = read_json(wd / "objects.json")
    views = {r["obj_id"]: r for r in read_json(wd / "step3_views.json")}
    frames = {f["frame_id"]: f for f in read_json(wd / "frames_all.json")}
    return objs, views, frames, read_json(wd / "step3_summary.json")


def official_typical_longest(cfg) -> dict[str, list[float]]:
    """Longest edge of the official annotation boxes (obb.axesLengths in segments_anno) over all 50 scenes, grouped by fine category;
    reads annotations only; used as the "typical size" reference."""
    mapping, _ = load_mapping(cfg)
    out = defaultdict(list)
    for sid in read_split(cfg):
        for gobj in json.load(open(sp_root(cfg) / "data" / sid / "scans" / "segments_anno.json"))["segGroups"]:
            m = mapping.get(gobj["label"])
            if m is None or m["kind"] != "object" or "obb" not in gobj:
                continue
            out[m["category_fine"]].append(float(max(gobj["obb"]["axesLengths"])))
    return out


def fmt_pct(x):
    return f"{x:.0%}"


def tile(img, h=240):
    s = h / img.shape[0]
    return cv2.resize(img, (max(1, int(img.shape[1] * s)), h), interpolation=cv2.INTER_AREA)


