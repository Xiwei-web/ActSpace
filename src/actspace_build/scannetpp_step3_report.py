    pick.sort(key=lambda x: x["ratio"])
    L += ["", "The 6 most changed objects (by new / PCA base-area ratio; including the copy machine of `5ee7c22ba0`). Red box = PCA, green box = new, drawn on the object's best-view keyframe:", ""]
