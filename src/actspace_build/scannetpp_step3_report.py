    L += [""]

    # ---------------- 6. clearly oversized boxes
    fac, exc = sp["outlier_size_factor"], sp["outlier_min_excess_m"]
    rr = sp["outlier_robust_ratio"]
    flagged = []
    for sid in pilots:
        for o in S[sid][0]:
            if o["kind"] != "object" or o["category_fine"] in STRUCT or o["category_fine"] not in allowed:
                continue
            lng = max(o["obb"]["size"][:2])
            c = o["category_fine"]
            reasons = []
            if len(typical.get(c, [])) >= 3 and lng > fac * typ_med[c] and lng - typ_med[c] >= exc:
                reasons.append(f"longest edge {lng:.2f} m > {fac}x class typical {typ_med[c]:.2f} m")
            rl = S[sid][1][o["obj_id"]]["robust_longest_m"]
            if rl and lng >= rr * rl and lng - rl >= exc * 0.6:
                reasons.append(f"longest edge after trimming {sp['outlier_robust_pct']}% of points at each end {rl:.2f} m (was {lng:.2f} m)")
