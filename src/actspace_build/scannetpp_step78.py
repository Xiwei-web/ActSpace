DATASET = "scannetpp"
VERSION = "scannetpp_only_v0.2"  # v0.1: GATE D verification version (work/scannetpp/_step8/scannetpp_only_v0.1/ is kept)


@contextlib.contextmanager
def as_scannetpp(*mods):
    old = [m.DATASET for m in mods]
    for m in mods:
        m.DATASET = DATASET
    try:
        yield
    finally:
        for m, o in zip(mods, old):
            m.DATASET = o


def names_of(cfg, sid):
    return {o["obj_id"]: o.get("ref_name") or o["category"] for o in read_json(sp_work(cfg) / sid.split("_", 1)[1] / "objects.json")}


# ---------------------------------------------------------------- Step 7
def grammar_check(cfg, groups, bank):
    """Grammar after substituting names: names must be singular (Step 7 is / are agreement); copulas directly after placeholders in the paraphrases; substitution examples for the exception names and window blind."""
    used = Counter()
    for g_ in groups:
        nm = names_of(cfg, g_["scene_id"])
        for q in g_["questions"]:
            used.update(nm[o] for o in q["slots"].values())
            used.update(nm[o] for o in q.get("option_objs") or [])
    plural_like = [n for n in used if re.search(r"(?<!s)s$", n.split()[-1]) and n not in ("glass",)]
    verbs = Counter()
    for k, v in bank.items():
        for p in [v["template"], *v["paraphrases"]]:
            for m in re.finditer(r"\{OBJ\d\}\s+(is|are|was|were|has|have|sits|sit|lies|lie)\b", p):
                verbs[(k, m.group(1))] += 1
    return used, plural_like, verbs


def step7(cfg):
    c = copy.deepcopy(cfg)
    out = sp_work(cfg) / "_step7"
    out.mkdir(parents=True, exist_ok=True)
    c["paths"]["build_info"] = str(out / "build_info.json")  # do not overwrite the repository-root build_info.json (ARKit)
    with as_scannetpp(step7_rewrite):
        val = step7_rewrite.validate(c)
        bad = [(k, r["id"]) for k, v in val.items() for r in v if r["errors"]]
        if bad:
            raise SystemExit(f"{len(bad)} paraphrases fail validation: {bad}")
        groups = step7_rewrite.apply(c)
        chi = step7_rewrite.chi_square(groups)
    bank = step7_rewrite.load_bank()
    used, plural_like, verbs = grammar_check(cfg, groups, bank)
    use = Counter((q["paraphrase_key"], q["paraphrase_id"]) for g_ in groups for q in g_["questions"])
    per_key = Counter(q["paraphrase_key"] for g_ in groups for q in g_["questions"])
    n_all = sum(len(v) for v in val.values())
    L = ["# ScanNet++ Step 7: question paraphrasing (reusing the template-level paraphrase bank)", "",
         "> Generated by `python -m actspace_build.scannetpp_step78 step7`. Method: see docs/data_construction.md (Step 7).",
         f"Reuses `configs/paraphrases.yaml` directly ({n_all} sentences, reviewed; SHA-256 `{step7_rewrite.bank_hash()}`), **with no edits or additions**. "
         "For each question, a scene-level seed `scene_rng(seed, scene_id, 'step7_rewrite')` picks one paraphrase of its template uniformly at random; the names are filled in and written to `text`, and the original template sentence is kept in `text_template`. "
         "The shared `step7_rewrite` is unchanged (the dataset is switched at run time); the record is written to `work/scannetpp/_step7/build_info.json`, not to the repository-root `build_info.json`.", "",
         f"Input `work/scannetpp/_step6/test_groups.jsonl` ({len(groups)} groups, {sum(per_key.values())} questions), output `work/scannetpp/_step7/test_groups.jsonl`. "
         f"Automatic validation of the paraphrase bank: {n_all - len(bad)} / {n_all} pass (same rules as ARKit, see `step7_rewrite.md`).", "",
         "## 1. Grammar check after substituting names", "",
         f"- Names actually used in ScanNet++ questions (slots + options): {len(used)}: " + ", ".join(f"{n} ({k})" for n, k in used.most_common()) + ".",
         f"- **Number**: all names are singular nouns (ending in s and looking plural: {', '.join(plural_like) or 'none'}; window blind was changed to singular). "
         "In every sentence of the bank the placeholder is preceded by 'the'; there are no indefinite articles, so a / an is not an issue.",
         "- **is / are**: copulas directly after a placeholder in the bank: " + (", ".join(f"{k} '{v}' {n} sentences" for (k, v), n in sorted(verbs.items())) or "none")
         + ". All names are singular, so after substitution is agrees with the subject; are does not occur.", ""]
    ex_names = [n for n in ("monitor", "copier", "window blind", "TV") if n in used]
    L += ["- **Substitution examples for the exception names and window blind** (paraphrase #0 of each template; the other placeholders use 'table', 'chair'):", "",
          "| Name | Template | After substitution |", "|---|---|---|"]
    for n in ex_names:
        for k in ("T1", "T2_closest", "T3", "T4", "T5"):
            p = bank[k]["paraphrases"][0]
            slots = {f"OBJ{i}": (n if i == 1 else "table" if i == 2 else "chair") for i in (1, 2, 3)}
            L.append(f"| {n} | {k} | {p.format(**{s: v for s, v in slots.items() if '{' + s + '}' in p})} |")
    L += ["", "Each substituted sentence above was checked and reads naturally ('the monitor', 'the copier', 'the window blind', 'the TV' work as standing point / facing / target). "
          "**No sentence reads awkwardly after substitution**, so the paraphrase bank needs no changes.", ""]
    L += ["## 2. Paraphrase usage counts", "", "| Template key | Questions | Uses per paraphrase (#0-#11) |", "|---|---|---|",
          *[f"| {k} | {per_key[k]} | {' / '.join(str(use[(k, i)]) for i in range(len(bank[k]['paraphrases'])))} |" for k in bank if per_key[k]], ""]
    rng = np.random.default_rng([cfg["seed"], 7, 1])
    qs = [(g_["scene_id"], q) for g_ in groups for q in g_["questions"]]
    pick = sorted(rng.choice(len(qs), min(50, len(qs)), replace=False).tolist())
    L += ["## 3. Before / after paraphrasing for 50 random questions", "", "| # | qid | Template sentence (names filled in) | Paraphrased |", "|---|---|---|---|"]
    for n_, i in enumerate(pick, 1):
        sid, q = qs[i]
        L.append(f"| {n_} | {q['qid']} | {step7_rewrite.fill(q['text_template'], q['slots'], names_of(cfg, sid))} | {q['text']} |")
    L += ["", "## 4. Association between paraphrase id and correct answer (chi-square + permutation test)", "",
          "For each template, a chi-square test of independence on the 'paraphrase id × correct answer' contingency table, plus a permutation-test p value (paraphrase ids shuffled 5000 times). "
          f"{len(chi)} tests in total; the multiple-testing-corrected significance threshold is about 0.05 / {len(chi)} ≈ {0.05 / len(chi):.4f}.", "",
          "| Template key | Answer variable | Questions | Table | χ² | dof | Chi-square p | Permutation p |", "|---|---|---|---|---|---|---|---|",
          *[f"| {k} | {name} | {n} | {shape[0]}×{shape[1]} | {chi2:.1f} | {dof} | {p:.3f} | {pp:.3f} |" for k, name, n, shape, chi2, dof, p, pp in chi]]
    sig = [r for r in chi if r[7] < 0.05 / len(chi)]
    L += ["", f"Conclusion: {len(sig)} tests significant after correction" + ("." if not sig else f" ({', '.join(f'{r[0]} {r[1]}' for r in sig)}).")
          + " Paraphrase selection uses only scene-level random numbers and is independent of the answer."]
    (path_of(cfg, "reports") / "scannetpp_step7_rewrite.md").write_text("\n".join(L) + "\n")
    print("wrote scannetpp_step7_rewrite.md;", len(groups), "groups;", "chi min perm p", min(r[7] for r in chi))


# ---------------------------------------------------------------- Step 8
def step8_cfg(cfg):
    c = copy.deepcopy(cfg)
    c["debias"]["output_version"] = VERSION
    # ScanNet++ does no question-removing quadrant balancing (deviations are only reported); option letters are balanced as usual
    c["questions"]["quadrant_balance_tol"] = 1.0
    c["debias"]["t4_front_back_tol"] = 1.0
    return c


def step8(cfg):
    c = step8_cfg(cfg)
    with as_scannetpp(step8_debias):
        step8_debias.run(c)
    rep = path_of(cfg, "reports")
    src = rep / f"step8_debias_{VERSION}.md"
    text = src.read_text()
    lines = text.split("\n")
    head = [f"# ScanNet++ Step 8: blind tests and debiasing (ScanNet++ alone -> {VERSION})", "",
            "> Generated by `python -m actspace_build.scannetpp_step78 step8`, reusing the shared module `step8_debias` (unchanged; the dataset is switched at run time). "
            "Method: see docs/data_construction.md (Step 8). The full pre-pruning question set `work/scannetpp/_step7/test_groups.jsonl` is kept unchanged; "
            "after merging with ARKit, Step 8 is rerun from the pre-pruning state.", "",
            "> **Difference from the shared method description below**: ScanNet++ does no question-removing quadrant balancing (at run time the T3/T4 quadrant tolerance and the T4 front/back tolerance are set to 1.0), "
            "so `RATIO_BALANCE` never occurs; quadrant deviations are only reported (see the post-pruning distribution). Option letters are reassigned uniformly per (template, number of options) as usual. "
            "No zero-shot LLM blind test was run (no external API calls).", ""]
    i = next(k for k, l in enumerate(lines) if l.startswith("Result:"))
    body = "\n".join(lines[i:]).replace("work/arkitscenes/", "work/scannetpp/")
    (rep / "scannetpp_step8_debias.md").write_text("\n".join(head) + "\n" + body)
    src.unlink()
    print("wrote scannetpp_step8_debias.md")


# ---------------------------------------------------------------- integrity check
def integrity_check(cfg):
    c = step8_cfg(cfg)
    stage = f"_step8/{VERSION}"
    out_name = f"{VERSION}_integrity_check.md"
    with as_scannetpp(integrity):
        groups, res, letters, quads, nonref = integrity.check(c, stage)
        integrity.write_report(c, groups, res, letters, quads, nonref, out_name=out_name, stage=stage)
    # ScanNet++ supplementary checks
    extra = {}

    def rec(item, ok, detail):
        extra.setdefault(item, [0, []])
        if ok:
            extra[item][0] += 1
        else:
            extra[item][1].append(detail)
    keys = {}
    for g_ in groups:
        vid = g_["scene_id"].split("_", 1)[1]
        black = load_blacklist(cfg, vid)
        nm = names_of(cfg, g_["scene_id"])
        for q in g_["questions"]:
            named = list(q["slots"].values()) + list(q.get("option_objs") or [])
            rec("No ScanNet++ blacklisted objects (configs/object_blacklist_scannetpp.yaml)", not (set(named) | set(q["evidence_objs"])) & set(black), q["qid"])
            k = (g_["scene_id"], dedup_key(q, True))
            keys[k] = keys.get(k, 0) + 1
            rec("Names are singular (no plural -s ending)", all(not re.search(r"(?<!s)s$", nm[o]) for o in named), q["qid"])
            rec("No larger / smaller in question text", not re.search(r"\b(larger|smaller)\b", q["text"], re.I), q["qid"])
    lim = cfg["questions"]["max_t4_per_object_per_scene"]
    for (sid, k), n in keys.items():
        rec("No duplicate T2 within a scene by reference object + direction + correct answer", n <= (lim if k[0] == "T4" else 1), f"{sid}: {k}")
    p = path_of(cfg, "reports") / out_name
    text = p.read_text().replace("work/arkitscenes/", "work/scannetpp/").replace("# ARKit", "# ScanNet++")
    # the match key is the check name emitted by integrity.check; keep it in sync with integrity.py
    text = text.replace("No blacklisted objects or excluded scenes", "No ARKit blacklisted objects or excluded scenes (always true for ScanNet++; see the ScanNet++ supplementary checks below)")
    L = ["", "## ScanNet++ supplementary checks", "", "| Check | Pass | Fail | Failure examples |", "|---|---|---|---|",
         *[f"| {k} | {v[0]} | {len(v[1])} | {'; '.join(map(str, v[1][:5])) or '—'} |" for k, v in extra.items()], "",
         "Note: the quadrant distribution is deliberately not balanced by removing questions, so failing the ±5% check is expected; balancing is done when Step 8 is rerun after merging with ARKit."]
    p.write_text(f"> ScanNet++ {VERSION} (`work/scannetpp/{stage}/test_groups.jsonl`); the shared `integrity` module with the dataset switched at run time.\n\n" + text + "\n".join(L) + "\n")
    append_step8_notes(cfg, res, extra, quads)
    print("wrote", p, {k: (v[0], len(v[1])) for k, v in extra.items()})


MARK = "\n## Appendix: integrity check and agent notes\n"


def append_step8_notes(cfg, res, extra, quads):
    """Append (or replace) the integrity-check summary and notes at the end of scannetpp_step8_debias.md; safe to rerun."""
    rp = path_of(cfg, "reports") / "scannetpp_step8_debias.md"
    body = rp.read_text().split(MARK)[0].rstrip("\n")
    n_items = len(res) + len(extra)
    bad = [k for k, (ok, b) in res.items() if b] + [k for k, v in extra.items() if v[1]]
    qdev = {t: max(abs(c[k] / sum(c.values()) - 0.25) for k in c) for t, c in quads.items() if sum(c.values())}
    m = read_json(sp_work(cfg) / "_step8" / VERSION / "manifest.json")
    # "| after debiasing |" and "**no**" are matched in the table written by step8_debias; keep in sync with it
    bad_after = [l.split("|")[1].strip() for l in body.split("\n") if "| after debiasing |" in l and "**no**" in l]
    note = ("After debiasing, every template passes the single blind test." if not bad_after else
            f"**Templates failing the single blind test after debiasing: {', '.join(bad_after)}** (iteration stopped once each template passed; the shared code then reshuffles option letters once more, "
            "so a single estimate fluctuates by a few percentage points; judge together with the 5 stability runs above).")
    L = [MARK.strip("\n"), "",
         f"Integrity check (applicable integrity-check items + ScanNet++ supplementary items, {n_items} in total): **{n_items - len(bad)} / {n_items} items pass 100%**"
         + (f"; failing: {', '.join(bad)}" if bad else "") + f". See `{VERSION}_integrity_check.md`.",
         "- Option letters: every (template, number of options) is within ± 5% of uniform.",
         "- Quadrants (no question-removing balancing, report only): " + ", ".join(f"{t} max deviation {d:.1%}" for t, d in sorted(qdev.items()))
         + ". T3 slightly exceeds ± 5%; this is left to the Step 8 rerun after merging with ARKit.", "",
         note, "",
         f"Outputs: `work/scannetpp/_step8/{VERSION}/test_groups.jsonl` ({m['groups']} groups, {m['questions']} questions) and `manifest.json`; "
         "full pre-pruning question set `work/scannetpp/_step7/test_groups.jsonl` (Step 8 is rerun from this state after merging)."]
    rp.write_text(body + "\n" + "\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["step7", "step8", "integrity"])
    args = ap.parse_args()
    cfg = load_config()
    {"step7": step7, "step8": step8, "integrity": integrity_check}[args.cmd](cfg)


if __name__ == "__main__":
    main()
