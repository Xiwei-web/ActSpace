"""ScanNet++ Step 7 (question paraphrasing) and Step 8 (standalone debiasing). Reuses the shared modules step7_rewrite /
step8_debias / integrity, switching their module-level DATASET to scannetpp only while running (ARKit code and behaviour
are unchanged).

  step7      reuses configs/paraphrases.yaml as is (no edits, no additions): validation, rewriting, grammar check of the
             substituted names, chi-square test -> reports/scannetpp_step7_rewrite.md
  step8      feature-only blind tests + two controls + 5 stability runs, iterative pruning per template
             -> work/scannetpp/_step8/<VERSION>/ (v0.1 is the GATE D verification version); no question-removing
             quadrant balancing, option letters are balanced as usual -> reports/scannetpp_step8_debias.md
  integrity  integrity check of <VERSION> (applicable integrity-check items + ScanNet++ blacklist, T2 dedup by answer,
             singular names) -> reports/<VERSION>_integrity_check.md

Usage: python -m actspace_build.scannetpp_step78 step7|step8|integrity
"""
